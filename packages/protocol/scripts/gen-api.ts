import { format } from "oxfmt";
import { isJsonObject, parseJson, type JsonObject, type JsonValue } from "../src/json.ts";
import {
  docComment,
  objectProperties,
  propertyKey,
  renderMembers,
  renderType,
  requiredSet,
  SchemaShapeError,
  type RenderContext,
} from "./schema-to-ts.ts";

const PACKAGE_DIR = new URL("..", import.meta.url).pathname;
export const SCHEMA_PATH = `${PACKAGE_DIR}schema/hc.openrpc.json`;
export const OUTPUT_PATH = `${PACKAGE_DIR}src/__generated__/hc-api.ts`;
const FORMAT_CONFIG_PATH = `${PACKAGE_DIR}../../.oxfmtrc.json`;

interface MethodShape {
  readonly name: string;
  readonly description: JsonValue | undefined;
  readonly params: JsonValue;
  readonly result: JsonValue;
}

export async function generateApi(schemaText: string): Promise<string> {
  const schema = parseJson(schemaText);
  if (!isJsonObject(schema)) throw new SchemaShapeError("schema root is not an object");
  const ctx: RenderContext = { imports: new Set() };
  const components = renderComponents(object(object(schema["components"])["schemas"]), ctx);
  const methods = array(schema["methods"]).map(methodShape);
  const body = [
    `export const HC_SCHEMA_VERSION = ${JSON.stringify(object(schema["info"])["version"])};`,
    "export type EmptyParams = { readonly [key: string]: never };",
    ...components,
    ...methods.map((method) => renderParams(method, ctx)),
    ...methods.flatMap((method) => renderResultAlias(method, ctx)),
    renderMethodMap(methods, ctx),
    "export type HcMethod = keyof HcMethods;",
    'export type HcParams<M extends HcMethod> = HcMethods[M]["params"];',
    'export type HcResult<M extends HcMethod> = HcMethods[M]["result"];',
    `export const HC_METHODS = [${methods.map((m) => JSON.stringify(m.name)).join(", ")}] as const satisfies readonly HcMethod[];`,
  ];
  const imports = [...ctx.imports].toSorted();
  const header = [
    "// Generated by packages/protocol/scripts/gen-api.ts from packages/protocol/schema/hc.openrpc.json.\n" +
      "// Do not edit: run `bun run --cwd packages/protocol gen:api` after updating the schema.",
    ...(imports.length > 0 ? [`import type { ${imports.join(", ")} } from "../json.ts";`] : []),
  ];
  return formatSource([...header, ...body].join("\n\n"));
}

function renderComponents(schemas: JsonObject, ctx: RenderContext): readonly string[] {
  return Object.entries(schemas).map(([name, node]) => {
    const doc = docComment(isJsonObject(node) ? node["description"] : undefined);
    if (isJsonObject(node) && node["type"] === "object" && objectProperties(node).length > 0) {
      return `${doc}export interface ${name} {\n${renderMembers(objectProperties(node), requiredSet(node), ctx)}\n}`;
    }
    return `${doc}export type ${name} = ${renderType(node, ctx)};`;
  });
}

function renderParams(method: MethodShape, ctx: RenderContext): string {
  const params = array(method.params).map(object);
  const name = `${typeBaseName(method.name)}Params`;
  if (params.length === 0) return `export type ${name} = EmptyParams;`;
  const properties = params.map((param) => [string(param["name"]), withDescription(param)] as const);
  const required = new Set(params.filter((param) => param["required"] === true).map((param) => string(param["name"])));
  return `export interface ${name} {\n${renderMembers(properties, required, ctx)}\n}`;
}

function renderResultAlias(method: MethodShape, ctx: RenderContext): readonly string[] {
  const type = renderType(object(method.result)["schema"], ctx);
  return resultIsNamed(type) ? [] : [`export type ${typeBaseName(method.name)}Result = ${type};`];
}

function renderMethodMap(methods: readonly MethodShape[], ctx: RenderContext): string {
  const entries = methods.map((method) => {
    const type = renderType(object(method.result)["schema"], ctx);
    const result = resultIsNamed(type) ? type : `${typeBaseName(method.name)}Result`;
    const params = `${typeBaseName(method.name)}Params`;
    return `${docComment(method.description)}readonly ${propertyKey(method.name)}: { readonly params: ${params}; readonly result: ${result} };`;
  });
  return `/** Every herdr-core JSON-RPC method with its params and result. */\nexport interface HcMethods {\n${entries.join("\n")}\n}`;
}

function resultIsNamed(type: string): boolean {
  return /^[A-Z]\w*$/.test(type) && type !== "JsonObject" && type !== "JsonValue";
}

function withDescription(param: JsonObject): JsonValue {
  const schema = object(param["schema"]);
  return schema["description"] === undefined ? { ...schema, description: param["description"] ?? null } : schema;
}

export function typeBaseName(method: string): string {
  return method
    .split(/[._]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

function methodShape(node: JsonValue): MethodShape {
  const method = object(node);
  return {
    name: string(method["name"]),
    description: method["description"],
    params: method["params"] ?? [],
    result: method["result"] ?? null,
  };
}

async function formatSource(source: string): Promise<string> {
  const config = object(parseJson(await Bun.file(FORMAT_CONFIG_PATH).text()));
  const printWidth = config["printWidth"];
  const result = await format("hc-api.ts", source, typeof printWidth === "number" ? { printWidth } : {});
  const [error] = result.errors;
  if (error !== undefined) throw new SchemaShapeError(`generated code does not parse: ${error.message}`);
  return result.code;
}

function object(value: JsonValue | undefined): JsonObject {
  if (!isJsonObject(value)) throw new SchemaShapeError(`expected an object, got ${JSON.stringify(value)}`);
  return value;
}

function array(value: JsonValue | undefined): readonly JsonValue[] {
  if (!Array.isArray(value)) throw new SchemaShapeError(`expected an array, got ${JSON.stringify(value)}`);
  return value;
}

function string(value: JsonValue | undefined): string {
  if (typeof value !== "string") throw new SchemaShapeError(`expected a string, got ${JSON.stringify(value)}`);
  return value;
}

if (import.meta.main) {
  const generated = await generateApi(await Bun.file(SCHEMA_PATH).text());
  if (process.argv.includes("--check")) {
    const committed = await Bun.file(OUTPUT_PATH).text();
    if (committed !== generated) {
      console.error(`${OUTPUT_PATH} is stale: run \`bun run --cwd packages/protocol gen:api\``);
      process.exitCode = 1;
    }
  } else {
    await Bun.write(OUTPUT_PATH, generated);
  }
}
